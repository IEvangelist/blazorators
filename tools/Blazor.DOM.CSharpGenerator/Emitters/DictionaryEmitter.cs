// Dictionary emitter: projects TypeScript interfaces matched to WebIDL "dictionary"
// classification into C# sealed records with init-only nullable properties.
// Preserves inheritance chain. Optional members -> nullable types.

using Blazor.DOM.CSharpGenerator.IR;
using Blazor.DOM.CSharpGenerator.Output;
using Blazor.DOM.CSharpGenerator.Projection;

namespace Blazor.DOM.CSharpGenerator.Emitters;

public sealed class DictionaryEmitter(TypeResolver typeResolver, string generatorVersion, string ns)
{
    /// <summary>
    /// Emits a C# record file for a symbol classified as a WebIDL dictionary.
    /// </summary>
    public string Emit(SymbolModel symbol)
    {
        // Use the first interface declaration (dictionaries appear as interfaces in TS)
        var decl = symbol.Declarations.FirstOrDefault(
            d => d.Kind is "interface" or "typeAlias")
            ?? throw new InvalidOperationException(
                $"DictionaryEmitter: '{symbol.Name}' has no interface/typeAlias declaration.");

        var csName = Naming.ToCSharpTypeName(symbol.Name);
        var baseClause = BuildBaseClause(decl);

        var w = new CSharpWriter();
        w.AppendLine(CSharpWriter.AutoGeneratedHeader("Blazor.DOM.CSharpGenerator", generatorVersion));
        w.AppendLine("using System.Text.Json.Serialization;");
        w.AppendLine();
        w.AppendLine($"namespace {ns};");
        w.AppendLine();

        var docText = decl.Documentation?.Text ?? "";
        var deprecated = decl.Documentation?.Deprecated ?? false;
        w.XmlDoc(docText, deprecated);

        if (symbol.Semantic.SecureContext)
            w.AppendLine("// Requires secure context (HTTPS).");
        if (symbol.Semantic.Serializable)
            w.AppendLine("// Serializable dictionary (supports structured clone).");

        var header = string.IsNullOrEmpty(baseClause)
            ? $"public record {csName}"
            : $"public record {csName} : {baseClause}";

        w.Block(header, () =>
        {
            var propertyMembers = decl.Members
                .Where(m => m.Kind is "property" or "getter")
                .OrderBy(m => m.Ordinal)
                .ToList();

            for (var i = 0; i < propertyMembers.Count; i++)
            {
                var member = propertyMembers[i];
                EmitProperty(w, member, symbol.Name);
                if (i < propertyMembers.Count - 1) w.AppendLine();
            }
        });

        return w.ToString();
    }

    private void EmitProperty(CSharpWriter w, MemberModel member, string symbolName)
    {
        var memberName = member.Name?.Text;
        if (memberName is null) return;

        var provenance = $"{symbolName}.{memberName}";
        TypeProjection projection;
        try
        {
            projection = typeResolver.Project(member.Type, provenance);
        }
        catch (TypeProjectionException ex)
        {
            // Emit a comment indicating the projection failed rather than crashing the whole type
            w.AppendLine($"// PROJECTION-FAILED: {memberName} -> {ex.Message.Replace('\n', ' ')}");
            return;
        }

        var docText = member.Documentation?.Text ?? "";
        var deprecated = member.Documentation?.Deprecated ?? false;
        w.XmlDoc(docText, deprecated);

        var csName = Naming.ToCSharpMemberName(memberName);
        var csType = projection.CSharpType;

        // Skip properties that resolve to 'null' (e.g., type?: undefined in TypeScript)
        if (csType is "null" or "void")
        {
            w.AppendLine($"// DEFERRED: {memberName} — type resolves to '{csType}' (undefined/void in TypeScript)");
            return;
        }

        // Optional members become nullable unless already nullable
        var nullable = member.Optional || projection.IsNullable;
        if (nullable && csType != "string" && csType != "object" && !csType.EndsWith("?")
            && !csType.StartsWith("IReadOnly") && !csType.EndsWith("[]"))
        {
            csType += "?";
        }

        // JsonPropertyName if the JS name differs from the PascalCase C# name
        if (!string.Equals(memberName, csName, StringComparison.Ordinal))
            w.AppendLine($"[JsonPropertyName(\"{memberName}\")]");

        if (member.Readonly)
            w.AppendLine($"public {csType} {csName} {{ get; init; }}");
        else
            w.AppendLine($"public {csType} {csName} {{ get; init; }}");
    }

    private static string BuildBaseClause(DeclarationModel decl)
    {
        var bases = decl.Heritage
            .Where(h => h.Token == "extends")
            .SelectMany(h => h.Types)
            .OfType<HeritageReferenceTypeNode>()
            .Select(t => Naming.ToCSharpTypeName(t.Expression))
            .ToList();
        return string.Join(", ", bases);
    }
}
