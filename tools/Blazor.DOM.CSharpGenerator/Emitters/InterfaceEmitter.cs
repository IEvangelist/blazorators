// Interface emitter: projects TypeScript interfaces matched to WebIDL "interface" or
// "mixin" classification into C# partial interface contracts.
// - Preserves inheritance chain from TS heritage
// - Properties -> C# properties
// - Methods -> C# method signatures
// - Event maps: explicitly accounted as deferred (no emission in this phase)
// - Index signatures and generic parameters: deferred or hard-error
// Host adapters (IJSRuntime calls) are NOT emitted here; the logical contract only.

using Blazor.DOM.CSharpGenerator.IR;
using Blazor.DOM.CSharpGenerator.Output;
using Blazor.DOM.CSharpGenerator.Projection;

namespace Blazor.DOM.CSharpGenerator.Emitters;

public sealed class InterfaceEmitter(TypeResolver typeResolver, string generatorVersion, string ns)
{
    /// <summary>
    /// Emits a C# partial interface for a symbol classified as WebIDL interface or mixin.
    /// </summary>
    public string Emit(SymbolModel symbol)
    {
        var decl = symbol.Declarations.FirstOrDefault(d => d.Kind == "interface")
            ?? throw new InvalidOperationException(
                $"InterfaceEmitter: '{symbol.Name}' has no interface declaration.");

        // If it's an event map, this should have been deferred before calling Emit
        if (decl.EventMap.IsEventMap)
            throw new InvalidOperationException(
                $"InterfaceEmitter: '{symbol.Name}' is an event map and should be deferred, not emitted.");

        var csName = Naming.ToCSharpTypeName(symbol.Name);
        var baseClause = BuildBaseClause(decl, typeResolver);

        var w = new CSharpWriter();
        w.AppendLine(CSharpWriter.AutoGeneratedHeader("Blazor.DOM.CSharpGenerator", generatorVersion));
        w.AppendLine($"namespace {ns};");
        w.AppendLine();

        var docText = decl.Documentation?.Text ?? "";
        var deprecated = decl.Documentation?.Deprecated ?? false;
        w.XmlDoc(docText, deprecated);

        if (symbol.Semantic.SecureContext)
            w.AppendLine("// Requires secure context (HTTPS).");
        if (symbol.Semantic.Transferable)
            w.AppendLine("// Transferable (supports postMessage transfer).");

        var header = string.IsNullOrEmpty(baseClause)
            ? $"public partial interface I{csName}"
            : $"public partial interface I{csName} : {baseClause}";

        w.Block(header, () =>
        {
            var emittedAny = false;

            // Properties (from getters and properties)
            var props = decl.Members
                .Where(m => m.Kind is "property" or "getter")
                .OrderBy(m => m.Ordinal)
                .ToList();

            foreach (var member in props)
            {
                if (EmitProperty(w, member, symbol.Name, decl)) emittedAny = true;
            }

            // Methods
            var methods = decl.Members
                .Where(m => m.Kind == "method" && m.Name is not null)
                .OrderBy(m => m.Ordinal)
                .ToList();

            foreach (var method in methods)
            {
                if (emittedAny || props.Any()) w.AppendLine();
                if (EmitMethod(w, method, symbol.Name)) emittedAny = true;
            }

            // Index signatures: deferred
            var indexSigs = decl.Members.Where(m => m.Kind == "indexSignature").ToList();
            if (indexSigs.Any())
            {
                w.AppendLine();
                w.AppendLine($"// DEFERRED: {indexSigs.Count} index signature(s) — deferred to index-accessor phase.");
            }

            // Call signatures: deferred
            var callSigs = decl.Members.Where(m => m.Kind == "callSignature").ToList();
            if (callSigs.Any())
            {
                w.AppendLine($"// DEFERRED: {callSigs.Count} call signature(s) — deferred to callable-interface phase.");
            }

            // Constructor signatures: deferred
            var ctorSigs = decl.Members.Where(m => m.Kind == "constructSignature").ToList();
            if (ctorSigs.Any())
            {
                w.AppendLine($"// DEFERRED: {ctorSigs.Count} constructor signature(s) — deferred to factory phase.");
            }
        });

        return w.ToString();
    }

    private bool EmitProperty(
        CSharpWriter w, MemberModel member, string symbolName, DeclarationModel decl)
    {
        var memberName = member.Name?.Text;
        if (memberName is null) return false;

        var provenance = $"{symbolName}.{memberName}";
        TypeProjection projection;
        try
        {
            projection = typeResolver.Project(member.Type, provenance);
        }
        catch (TypeProjectionException ex) when (ex.Message.Contains("deferred to the events phase"))
        {
            w.AppendLine($"// DEFERRED (events): {memberName} — {ex.Provenance}");
            return true;
        }
        catch (TypeProjectionException ex)
        {
            w.AppendLine($"// PROJECTION-FAILED: {memberName} — {ex.Message.Replace('\n', ' ').Substring(0, Math.Min(120, ex.Message.Length))}");
            return true;
        }

        var docText = member.Documentation?.Text ?? "";
        var deprecated = member.Documentation?.Deprecated ?? false;
        w.XmlDoc(docText, deprecated);

        var csName = Naming.ToCSharpMemberName(memberName);
        var csType = projection.CSharpType;

        // Skip properties that resolve to 'null' (e.g., type?: undefined in TS)
        if (csType is "null" or "void")
        {
            w.AppendLine($"// DEFERRED: {memberName} — type resolves to '{csType}' (undefined/void in TypeScript)");
            return true;
        }

        if ((member.Optional || projection.IsNullable)
            && !csType.EndsWith("?") && !csType.StartsWith("IReadOnly")
            && !csType.EndsWith("[]") && csType != "string" && csType != "object")
        {
            csType += "?";
        }

        var hasSetter = decl.Members.Any(m =>
            m.Kind == "setter" && m.Name?.Text == memberName);

        if (member.Readonly || !hasSetter)
            w.AppendLine($"{csType} {csName} {{ get; }}");
        else
            w.AppendLine($"{csType} {csName} {{ get; set; }}");

        return true;
    }

    private bool EmitMethod(CSharpWriter w, MemberModel method, string symbolName)
    {
        var memberName = method.Name?.Text;
        if (memberName is null) return false;

        var provenance = $"{symbolName}.{memberName}";

        TypeProjection returnProj;
        try
        {
            returnProj = typeResolver.Project(method.ReturnType, $"{provenance}/return");
        }
        catch (TypeProjectionException ex)
        {
            w.AppendLine($"// PROJECTION-FAILED: {memberName}() return — {ex.Message.Replace('\n', ' ').Substring(0, Math.Min(120, ex.Message.Length))}");
            return true;
        }

        var docText = method.Documentation?.Text ?? "";
        var deprecated = method.Documentation?.Deprecated ?? false;
        w.XmlDoc(docText, deprecated);

        var csName = Naming.ToCSharpMemberName(memberName);
        var csReturn = returnProj.CSharpType;

        var paramParts = new List<string>();
        foreach (var p in method.Parameters.OrderBy(p => p.Ordinal))
        {
            string pType;
            try
            {
                var pProj = typeResolver.Project(p.Type, $"{provenance}/{p.Name}");
                pType = pProj.IsNullable && !pProj.CSharpType.EndsWith("?")
                    ? pProj.CSharpType + "?"
                    : pProj.CSharpType;
            }
            catch (TypeProjectionException)
            {
                pType = "object";
            }
            var pName = Naming.ToCSharpParameterName(p.Name);
            if (p.Rest)
                paramParts.Add($"params {pType}[] {pName}");
            else if (p.Optional)
                paramParts.Add($"{pType} {pName} = default");
            else
                paramParts.Add($"{pType} {pName}");
        }

        var paramList = string.Join(", ", paramParts);

        // Promise<T> return types become async ValueTask
        if (csReturn.StartsWith("ValueTask"))
            w.AppendLine($"{csReturn} {csName}Async({paramList});");
        else
            w.AppendLine($"{csReturn} {csName}({paramList});");

        return true;
    }

    private static string BuildBaseClause(DeclarationModel decl, TypeResolver typeResolver)
    {
        var bases = decl.Heritage
            .Where(h => h.Token == "extends")
            .SelectMany(h => h.Types)
            .OfType<HeritageReferenceTypeNode>()
            // Skip TypeScript built-in heritage types not present in the Web API symbol index
            .Where(t => typeResolver.IsKnownSymbol(t.Expression))
            .Select(t => $"I{Naming.ToCSharpTypeName(t.Expression)}")
            .ToList();
        return string.Join(", ", bases);
    }
}
