// Callback emitter: projects TypeScript typeAlias/interface symbols matched to WebIDL
// "callback" or "callbackInterface" classification into C# delegates.
// Handles call signatures and function type aliases.

using Blazor.DOM.CSharpGenerator.IR;
using Blazor.DOM.CSharpGenerator.Output;
using Blazor.DOM.CSharpGenerator.Projection;

namespace Blazor.DOM.CSharpGenerator.Emitters;

public sealed class CallbackEmitter(TypeResolver typeResolver, string generatorVersion, string ns)
{
    /// <summary>
    /// Emits a C# delegate for a symbol classified as a WebIDL callback/callbackInterface.
    /// </summary>
    public string Emit(SymbolModel symbol)
    {
        // Extract signature from the declaration
        var (parameters, returnType) = ExtractSignature(symbol);

        var w = new CSharpWriter();
        w.AppendLine(CSharpWriter.AutoGeneratedHeader("Blazor.DOM.CSharpGenerator", generatorVersion));
        w.AppendLine($"namespace {ns};");
        w.AppendLine();

        var docText = GetDocText(symbol);
        var deprecated = IsDeprecated(symbol);
        w.XmlDoc(docText, deprecated);

        if (symbol.Semantic.SecureContext)
            w.AppendLine("// Requires secure context (HTTPS).");

        var csName = Naming.ToCSharpTypeName(symbol.Name);
        var paramList = BuildParamList(parameters, symbol.Name);
        w.AppendLine($"public delegate {returnType} {csName}({paramList});");

        return w.ToString();
    }

    private (IReadOnlyList<ParameterModel> Params, string ReturnType) ExtractSignature(SymbolModel symbol)
    {
        // Case 1: typeAlias with FunctionTypeNode type
        var typeAliasDecl = symbol.Declarations.FirstOrDefault(d => d.Kind == "typeAlias");
        if (typeAliasDecl?.Type is FunctionTypeNode fn)
        {
            var ret = ProjectReturnType(fn.ReturnType, $"{symbol.Name}/return");
            return (fn.Parameters, ret);
        }

        // Case 2: interface with a single callSignature member
        var interfaceDecl = symbol.Declarations.FirstOrDefault(d => d.Kind == "interface");
        if (interfaceDecl is not null)
        {
            var callSig = interfaceDecl.Members.FirstOrDefault(m => m.Kind == "callSignature");
            if (callSig is not null)
            {
                var ret = ProjectReturnType(callSig.ReturnType, $"{symbol.Name}/return");
                return (callSig.Parameters, ret);
            }
        }

        // Case 3: typeAlias with a union (some callbacks are alias of function | null)
        if (typeAliasDecl?.Type is UnionTypeNode un)
        {
            var fnType = un.Types.OfType<FunctionTypeNode>().FirstOrDefault();
            if (fnType is not null)
            {
                var ret = ProjectReturnType(fnType.ReturnType, $"{symbol.Name}/return");
                return (fnType.Parameters, ret);
            }
        }

        throw new InvalidOperationException(
            $"CallbackEmitter: '{symbol.Name}' has no extractable call signature. " +
            "Expected: typeAlias with FunctionTypeNode, or interface with callSignature.");
    }

    private string ProjectReturnType(TypeNode? returnType, string provenance)
    {
        if (returnType is null) return "void";
        try
        {
            var proj = typeResolver.Project(returnType, provenance);
            return proj.CSharpType;
        }
        catch (TypeProjectionException)
        {
            return "void";
        }
    }

    private string BuildParamList(IReadOnlyList<ParameterModel> parameters, string symbolName)
    {
        var parts = new List<string>(parameters.Count);
        foreach (var p in parameters.OrderBy(p => p.Ordinal))
        {
            string csType;
            try
            {
                var proj = typeResolver.Project(p.Type, $"{symbolName}/{p.Name}");
                csType = proj.IsNullable && !proj.CSharpType.EndsWith("?")
                    ? proj.CSharpType + "?"
                    : proj.CSharpType;
            }
            catch (TypeProjectionException)
            {
                csType = "object";
            }

            var csParam = Naming.ToCSharpParameterName(p.Name);
            if (p.Rest)
                parts.Add($"params {csType}[] {csParam}");
            else
                parts.Add($"{csType} {csParam}");
        }
        return string.Join(", ", parts);
    }

    private static string GetDocText(SymbolModel symbol)
    {
        return symbol.Declarations
            .Select(d => d.Documentation?.Text)
            .FirstOrDefault(t => !string.IsNullOrEmpty(t)) ?? "";
    }

    private static bool IsDeprecated(SymbolModel symbol)
    {
        return symbol.Declarations.Any(d => d.Documentation?.Deprecated ?? false);
    }
}
